"""Server-side storage for the Sticky Board (static/vendor/sticky-board/,
a vendored third-party Kanban-style note board, see PROVENANCE.md there).

Multiple independently-named boards, each optionally linked to a project
folder (api/models.py's load_projects()/PROJECTS_FILE -- the WebUI's own
lightweight Projects entity, not the separate WORKSPACES.yaml registry in
api/project_registry.py). Storage is a flat JSON document at
STATE_DIR/sticky_boards.json, unscoped by hermes-agent profile -- the same
STATE_DIR every profile's WebUI session shares -- so a board's project link
holds regardless of which profile is active.

Project linkage sync: when a board is linked to a project that has a bound
workspace_path, this module mirrors the board's content into a clearly
delimited section of that workspace's AGENTS.md. That file is a real,
already-proven ingestion path -- api/routes.py's _project_context_candidates()
(the WebUI's own read-only mirror of it) confirms AGENTS.md at a project's
workspace root is the first thing hermes-agent looks for and injects into
every chat's context for that project. This module owns writing it (no
other code in this repo writes to it); the delimiters keep the sync
idempotent and never touch the rest of the file, so a user's own AGENTS.md
content is left alone.
"""
import json
import re
import time
import uuid

from api.config import STATE_DIR

BOARDS_FILE = STATE_DIR / "sticky_boards.json"
# Pre-multi-board era: a single global board at this path. Migrated into
# the first entry of BOARDS_FILE the first time load_boards() runs against
# an instance that has this but not yet BOARDS_FILE.
_LEGACY_BOARD_FILE = STATE_DIR / "sticky_board.json"

_MARKER_START = "<!-- hermes-webui:sticky-board:{board_id} start (auto-generated by the Notes panel -- edit the linked board there, not here) -->"
_MARKER_END = "<!-- hermes-webui:sticky-board:{board_id} end -->"


def load_boards() -> list:
    if BOARDS_FILE.exists():
        try:
            data = json.loads(BOARDS_FILE.read_text(encoding="utf-8"))
        except Exception:
            return []
        boards = data.get("boards") if isinstance(data, dict) else None
        return boards if isinstance(boards, list) else []
    if _LEGACY_BOARD_FILE.exists():
        try:
            legacy = json.loads(_LEGACY_BOARD_FILE.read_text(encoding="utf-8"))
        except Exception:
            legacy = None
        if isinstance(legacy, dict) and isinstance(legacy.get("columns"), list):
            board = {
                "id": uuid.uuid4().hex[:12],
                "name": "My Board",
                "project_id": None,
                "columns": legacy["columns"],
                "created_at": time.time(),
                "updated_at": time.time(),
            }
            save_boards([board])
            return [board]
    return []


def save_boards(boards) -> None:
    BOARDS_FILE.write_text(json.dumps({"boards": boards}, ensure_ascii=False, indent=2), encoding="utf-8")


def get_board(board_id: str):
    for b in load_boards():
        if b.get("id") == board_id:
            return b
    return None


def create_board(name: str, project_id: str | None = None) -> dict:
    boards = load_boards()
    now = time.time()
    board = {
        "id": uuid.uuid4().hex[:12],
        "name": (name or "New Board")[:128],
        "project_id": project_id or None,
        "columns": [],
        "created_at": now,
        "updated_at": now,
    }
    boards.append(board)
    save_boards(boards)
    _sync_board_to_agents_md(board)
    return board


def rename_board(board_id: str, name: str):
    boards = load_boards()
    for b in boards:
        if b.get("id") == board_id:
            b["name"] = (name or b["name"])[:128]
            b["updated_at"] = time.time()
            save_boards(boards)
            _sync_board_to_agents_md(b)
            return b
    return None


def delete_board(board_id: str) -> bool:
    boards = load_boards()
    target = next((b for b in boards if b.get("id") == board_id), None)
    if target is None:
        return False
    _remove_board_from_agents_md(target)
    save_boards([b for b in boards if b.get("id") != board_id])
    return True


def set_board_project(board_id: str, project_id: str | None):
    boards = load_boards()
    for b in boards:
        if b.get("id") == board_id:
            old_project_id = b.get("project_id")
            if old_project_id and old_project_id != project_id:
                _remove_board_from_agents_md(b, project_id_override=old_project_id)
            b["project_id"] = project_id or None
            b["updated_at"] = time.time()
            save_boards(boards)
            _sync_board_to_agents_md(b)
            return b
    return None


def save_board_columns(board_id: str, columns: list):
    boards = load_boards()
    for b in boards:
        if b.get("id") == board_id:
            b["columns"] = columns
            b["updated_at"] = time.time()
            save_boards(boards)
            _sync_board_to_agents_md(b)
            return b
    return None


# ── AGENTS.md sync ──────────────────────────────────────────────────────
def _project_workspace_path(project_id: str):
    """Look up a project's bound workspace_path without importing
    api/routes.py (which imports this module -- avoid a cycle). Reads
    load_projects() directly from api.models, the same source routes.py's
    project handlers already use."""
    try:
        from api.models import load_projects
    except Exception:
        return None
    for p in load_projects():
        if p.get("project_id") == project_id:
            path = p.get("workspace_path")
            return str(path) if path else None
    return None


def _resolve_agents_md_path(workspace_path: str):
    """Validate workspace_path the same way /api/projects/set_workspace
    does before ever writing to it, and return the AGENTS.md path inside
    it -- or None if the path isn't a real, allowed workspace."""
    try:
        from api.workspace import resolve_trusted_workspace, is_blocked_system_path
    except Exception:
        return None
    try:
        resolved = resolve_trusted_workspace(workspace_path)
    except ValueError:
        return None
    if is_blocked_system_path(str(resolved)):
        return None
    if not resolved.is_dir():
        return None
    return resolved / "AGENTS.md"


def _render_board_section(board: dict) -> str:
    lines = ["## Sticky Notes -- " + (board.get("name") or "Untitled board")]
    for col in board.get("columns") or []:
        lines.append("")
        lines.append("- **" + str(col.get("title") or "Untitled column") + "**")
        for note in col.get("notes") or []:
            lines.append("  - " + str(note.get("title") or ""))
            for sub in note.get("subItems") or []:
                if sub:
                    lines.append("    - " + str(sub))
    return "\n".join(lines) + "\n"


def _replace_or_append_section(content: str, board_id: str, section_body: str | None) -> str:
    """section_body=None removes the section entirely; otherwise replaces
    it in place if present, or appends it if not."""
    start_marker = _MARKER_START.format(board_id=board_id)
    end_marker = _MARKER_END.format(board_id=board_id)
    pattern = re.compile(re.escape(start_marker) + r".*?" + re.escape(end_marker) + r"\n?", re.DOTALL)

    if section_body is None:
        return pattern.sub("", content)

    block = start_marker + "\n" + section_body + end_marker + "\n"
    if pattern.search(content):
        return pattern.sub(block, content)
    sep = "\n" if content and not content.endswith("\n") else ""
    return content + sep + ("\n" if content else "") + block


def _sync_board_to_agents_md(board: dict) -> None:
    project_id = board.get("project_id")
    if not project_id:
        return
    workspace_path = _project_workspace_path(project_id)
    if not workspace_path:
        return
    agents_md = _resolve_agents_md_path(workspace_path)
    if agents_md is None:
        return
    try:
        existing = agents_md.read_text(encoding="utf-8") if agents_md.exists() else ""
        updated = _replace_or_append_section(existing, board["id"], _render_board_section(board))
        agents_md.write_text(updated, encoding="utf-8")
    except Exception:
        pass  # Best-effort -- a write failure here must never break board saving.


def _remove_board_from_agents_md(board: dict, project_id_override: str | None = None) -> None:
    project_id = project_id_override if project_id_override is not None else board.get("project_id")
    if not project_id:
        return
    workspace_path = _project_workspace_path(project_id)
    if not workspace_path:
        return
    agents_md = _resolve_agents_md_path(workspace_path)
    if agents_md is None or not agents_md.exists():
        return
    try:
        existing = agents_md.read_text(encoding="utf-8")
        updated = _replace_or_append_section(existing, board["id"], None)
        if updated != existing:
            agents_md.write_text(updated, encoding="utf-8")
    except Exception:
        pass
